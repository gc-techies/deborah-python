# Operators that accept one operand are called unary operators. For example, the negation operator (-) is a unary operator that negates the value of its operand.
# Operators that accept two operands are called binary operators. For example, the addition operator (+) is a binary operator that adds two operands together.
# Operators that accept three operands are called ternary operators. For example, the conditional operator (?:) is a ternary operator that evaluates a condition and returns one of two values based on the result of the evaluation.

# ARITHMETIC OPERATORS: +, -, *, /, %, **, //
print(f"2 + 2 = {2 + 2}")  # addition
print(f"2 - 2 = {2 - 2}")  # subtraction
print(f"2 * 2 = {2 * 2}")  # multiplication
print(f"5 / 2 = {5 / 2}")  # division
print(f"5 // 2 = {5 // 2}")  # floor division
print(f"5 % 2 = {5 % 2}")  # modulo operation
print(f"2 ** 3 = {2 ** 3}")  # exponentiation