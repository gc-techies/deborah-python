# we use comparison operators to compare two values and return a boolean value (True or False)
# comparison operators: ==, !=, >, <, >=, <=

print(f"2 == 2: {2 == 2}")  # equal to (equality operator)
print(f"2 != 2: {2 != 2}")  # not equal to (inequality operator)
print(f"2 > 2: {2 > 2}")  # greater than (greater than operator)
print(f"2 < 2: {2 < 2}")  # less than (less than operator)
print(f"2 >= 2: {2 >= 2}")  # greater than or equal to (greater than or equal to operator)
print(f"2 <= 2: {2 <= 2}")  # less than or equal to (less than or equal to operator)
print(f"10 == '10': {10 == '10'}")  # equal to (equality operator)
print(f"bag == bag : {'bag' == 'bag'}")  # equal to (equality operator)
print(f"bag == Bag : {'bag' == 'Bag'}")  # equal to (equality operator)

